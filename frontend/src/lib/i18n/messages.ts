const LATAM = new Set([
  'AR', 'BO', 'CL', 'CO', 'CR', 'CU', 'DO', 'EC', 'SV', 'GT', 'HN', 'MX', 'NI', 'PA', 'PY', 'PE', 'PR', 'UY', 'VE',
])

const FRENCH = new Set([
  'FR', 'MC', 'BE', 'LU', 'SN', 'CI', 'CM', 'ML', 'BF', 'NE', 'TG', 'BJ', 'GA', 'CG', 'CD', 'MG', 'HT', 'GN', 'RW', 'BI', 'DJ', 'KM', 'TD', 'CF', 'GQ',
])

export function localeFromCountry(code: string | undefined): Locale | null {
  const country = String(code || '').toUpperCase()
  if (country === 'BR') return 'pt'
  if (country === 'AE') return 'ar'
  if (country === 'US' || LATAM.has(country)) return 'es'
  if (FRENCH.has(country)) return 'fr'
  return null
}

export function localeFromNavigator(language: string | undefined): Locale {
  const tag = String(language || '').toLowerCase()
  if (tag.startsWith('pt')) return 'pt'
  if (tag.startsWith('es')) return 'es'
  if (tag.startsWith('ar')) return 'ar'
  if (tag.startsWith('fr')) return 'fr'
  return 'en'
}

